import { Dataset, PlotSpec } from "../types";
import {
  pystr,
  embedData,
  isHorizontal,
  axisScale,
  mplLineStyle,
  mplMarker,
  aggregateCode,
  resolvedSpec,
} from "./pgenHelpers";

export type PythonGraphLibrary = "plotly" | "matplotlib" | "seaborn" | "altair";

function axisSetupLines(spec: PlotSpec): string[] {
  const horizontal = isHorizontal(spec);
  const showAxisLabels = spec.showAxisLabels !== false;
  const lines = [
    `ax.set_xlabel(${pystr(showAxisLabels ? (horizontal ? (spec.yLabel || spec.yVar) : (spec.xLabel || spec.xVar)) : "")})`,
    `ax.set_ylabel(${pystr(showAxisLabels ? (horizontal ? (spec.xLabel || spec.xVar) : (spec.yLabel || spec.yVar)) : "")})`,
  ];
  if (spec.title) lines.unshift(`ax.set_title(${pystr(spec.title)})`);
  lines.push(`ax.tick_params(axis="x", labelbottom=${spec.showXTicks ? "True" : "False"})`);
  lines.push(`ax.tick_params(axis="y", labelleft=${spec.showYTicks ? "True" : "False"})`);
  lines.push(`plt.setp(ax.get_xticklabels(), rotation=${spec.xTickAngle}, ha=${spec.xTickAngle === 0 ? '"center"' : '"right"'})`);
  lines.push(`plt.setp(ax.get_yticklabels(), rotation=${spec.yTickAngle})`);
  if (spec.xTickStep !== "") lines.push(`ax.xaxis.set_major_locator(plt.MultipleLocator(${spec.xTickStep}))`);
  if (spec.yTickStep !== "") lines.push(`ax.yaxis.set_major_locator(plt.MultipleLocator(${spec.yTickStep}))`);
  if (spec.xMinorTickStep !== "") lines.push(`ax.xaxis.set_minor_locator(plt.MultipleLocator(${spec.xMinorTickStep}))`);
  if (spec.yMinorTickStep !== "") lines.push(`ax.yaxis.set_minor_locator(plt.MultipleLocator(${spec.yMinorTickStep}))`);
  if (spec.xMin !== "" && spec.xMax !== "") lines.push(`ax.set_xlim(${spec.xMin}, ${spec.xMax})`);
  if (spec.yMin !== "" && spec.yMax !== "") lines.push(`ax.set_ylim(${spec.yMin}, ${spec.yMax})`);
  if (spec.xReverse) lines.push("ax.invert_xaxis()");
  if (spec.yReverse) lines.push("ax.invert_yaxis()");
  if (axisScale(spec.xScale) === "log") lines.push('ax.set_xscale("log")');
  if (axisScale(spec.yScale, spec.logY) === "log") lines.push('ax.set_yscale("log")');
  if (spec.xPrefix || spec.xSuffix) lines.push(`ax.xaxis.set_major_formatter(lambda v, pos: ${pystr(spec.xPrefix)} + format(v, "g") + ${pystr(spec.xSuffix)})`);
  if (spec.yPrefix || spec.ySuffix) lines.push(`ax.yaxis.set_major_formatter(lambda v, pos: ${pystr(spec.yPrefix)} + format(v, "g") + ${pystr(spec.ySuffix)})`);
  if (spec.showGrid) lines.push("ax.grid(True, alpha=0.25)");
  else lines.push("ax.grid(False)");
  lines.push(`ax.tick_params(direction=${pystr(spec.xTickDirection === "inside" ? "in" : spec.xTickDirection === "center" ? "inout" : "out")}, width=1)`);
  return lines;
}

export function generateMatplotlibPython(spec: PlotSpec, ds: Dataset, useSeaborn: boolean): string {
  spec = resolvedSpec(spec, ds);
  const lines: string[] = [
    `# Generated by Iris — Python ${useSeaborn ? "seaborn" : "matplotlib"} equivalent.`,
    "import numpy as np",
    "import pandas as pd",
    "import matplotlib.pyplot as plt",
    useSeaborn ? "import seaborn as sns" : "",
    "from io import StringIO",
    "",
    embedData(ds),
    "",
    "fig, ax = plt.subplots(figsize=(7, 5), dpi=120)",
  ].filter(Boolean);

  if (!spec.xVar || !spec.yVar) {
    lines.push('ax.text(0.5, 0.5, "Add data or assign graph fields to render this chart.", ha="center", va="center", transform=ax.transAxes)');
    lines.push("ax.axis('off')");
    lines.push("fig.tight_layout()");
    lines.push("plt.show()");
    return lines.join("\n");
  }

  const x = pystr(spec.xVar);
  const y = pystr(spec.yVar);
  const group = spec.groupVar ? pystr(spec.groupVar) : "";
  const hue = spec.colorVar ? pystr(spec.colorVar) : group;
  const yNumeric = ds.types[spec.yVar] === "numeric";
  const horizontal = isHorizontal(spec);
  const marker = pystr(mplMarker(spec));
  const markColor = spec.markColor ? `, color=${pystr(spec.markColor)}` : "";
  const scatterGradient = spec.colorVar ? `, c=df[${pystr(spec.colorVar)}], cmap=${pystr(spec.contColorScale.toLowerCase())}` : "";
  const seabornPalette = spec.colorVar ? `, palette=${pystr(spec.contColorScale.toLowerCase())}` : "";
  const lineColor = spec.lineColor || spec.markColor ? `, color=${pystr(spec.lineColor || spec.markColor)}` : "";
  const lineStyle = `, linestyle=${pystr(mplLineStyle(spec))}`;

  if (useSeaborn) {
    lines.push('sns.set_theme(style="whitegrid" if ' + (spec.showGrid ? "True" : "False") + ' else "white")');
  }
  if (spec.backgroundColor) {
    lines.push(`fig.patch.set_facecolor(${pystr(spec.backgroundColor)})`);
    lines.push(`ax.set_facecolor(${pystr(spec.backgroundColor)})`);
  }

  switch (spec.graphType) {
    case "histogram":
      lines.push(useSeaborn
        ? `sns.histplot(data=df, x=${x}${group ? `, hue=${group}` : ""}, bins=${spec.histBins}, stat=${pystr(spec.histNorm === "count" ? "count" : spec.histNorm)}, ax=ax)`
        : `ax.hist(df[${x}].dropna(), bins=${spec.histBins}, alpha=${spec.opacity})`);
      break;
    case "density":
      lines.push(useSeaborn
        ? `sns.kdeplot(data=df, x=${x}${group ? `, hue=${group}` : ""}, fill=True, alpha=${Math.min(spec.opacity, 0.6)}, ax=ax)`
        : `df[${x}].dropna().plot(kind="density", ax=ax)`);
      break;
    case "box":
      lines.push(useSeaborn
        ? `sns.boxplot(data=df, ${horizontal ? `x=${y}, y=${pystr(spec.groupVar || spec.xVar)}` : `x=${pystr(spec.groupVar || spec.xVar)}, y=${y}`}, ax=ax)`
        : `df.boxplot(column=${y}, by=${pystr(spec.groupVar || spec.xVar)}, ax=ax)`);
      if (horizontal && !useSeaborn) lines.push("ax.invert_yaxis()");
      break;
    case "violin":
      lines.push(useSeaborn
        ? `sns.violinplot(data=df, ${horizontal ? `x=${y}, y=${pystr(spec.groupVar || spec.xVar)}` : `x=${pystr(spec.groupVar || spec.xVar)}, y=${y}`}, ax=ax)`
        : `ax.violinplot([g[${y}].dropna().values for _, g in df.groupby(${pystr(spec.groupVar || spec.xVar)})])`);
      break;
    case "strip":
    case "beeswarm":
      lines.push(useSeaborn
        ? `sns.stripplot(data=df, ${horizontal ? `x=${y}, y=${pystr(spec.groupVar || spec.xVar)}` : `x=${pystr(spec.groupVar || spec.xVar)}, y=${y}`}, hue=${group || "None"}, ax=ax)`
        : `ax.scatter(df[${x}], df[${y}], s=${spec.pointSize * 5}, marker=${marker}, alpha=${spec.opacity}${markColor})`);
      break;
    case "bar":
    case "lollipop":
      lines.push(aggregateCode(spec, ds));
      lines.push(`value_col = ${yNumeric ? y : '"count"'}`);
      lines.push(useSeaborn
        ? `sns.barplot(data=agg, ${horizontal ? `x=value_col, y=${x}` : `x=${x}, y=value_col`}, ax=ax)`
        : horizontal ? `ax.barh(agg[${x}], agg[value_col], height=${spec.barWidth}, alpha=${spec.opacity}, linewidth=${spec.barBorderWidth}, edgecolor="black", hatch=${pystr(spec.fillPattern === "hatch" ? "/" : "")})` : `ax.bar(agg[${x}], agg[value_col], width=${spec.barWidth}, alpha=${spec.opacity}, linewidth=${spec.barBorderWidth}, edgecolor="black", hatch=${pystr(spec.fillPattern === "hatch" ? "/" : "")})`);
      if (spec.graphType === "lollipop") lines.push(horizontal ? `ax.scatter(agg[value_col], agg[${x}], s=${spec.pointSize * 8}, marker=${marker}, color=${pystr(spec.markColor || "black")}, zorder=3)` : `ax.scatter(agg[${x}], agg[value_col], s=${spec.pointSize * 8}, marker=${marker}, color=${pystr(spec.markColor || "black")}, zorder=3)`);
      if (spec.showDropSpikes) lines.push(horizontal ? `ax.hlines(agg[${x}], 0, agg[value_col], linewidth=${Math.max(0.5, spec.lineWidth * 0.45)}, linestyles=${pystr(mplLineStyle(spec))})` : `ax.vlines(agg[${x}], 0, agg[value_col], linewidth=${Math.max(0.5, spec.lineWidth * 0.45)}, linestyles=${pystr(mplLineStyle(spec))})`);
      break;
    case "line":
    case "timeSeries":
    case "connected":
      lines.push(useSeaborn
        ? `sns.lineplot(data=df, x=${x}, y=${y}${group ? `, hue=${group}` : ""}, marker=${spec.showPoints || spec.graphType === "connected" ? '"o"' : "None"}, ax=ax)`
        : `ax.plot(df[${x}], df[${y}], ${spec.showPoints || spec.graphType === "connected" ? pystr(mplMarker(spec) + mplLineStyle(spec)) : pystr(mplLineStyle(spec))}, linewidth=${spec.lineWidth}${lineColor})`);
      if (spec.showDirectionalArrows) lines.push(`ax.scatter(df[${x}].iloc[-1], df[${y}].iloc[-1], marker=">", s=${(spec.pointSize + 4) * 8}${lineColor})`);
      break;
    case "step":
      lines.push(`ax.step(df[${x}], df[${y}], where="post", linewidth=${spec.lineWidth}${lineColor}${lineStyle})`);
      if (spec.showDirectionalArrows) lines.push(`ax.scatter(df[${x}].iloc[-1], df[${y}].iloc[-1], marker=">", s=${(spec.pointSize + 4) * 8}${lineColor})`);
      break;
    case "area":
    case "stackedArea":
      lines.push(`ax.fill_between(df[${x}], df[${y}], alpha=${Math.min(spec.opacity, 0.65)})`);
      break;
    case "heatmap":
      lines.push(`heat = df.pivot_table(index=${pystr(spec.groupVar || spec.yVar)}, columns=${x}, values=${y}, aggfunc="mean")`);
      lines.push(useSeaborn ? "sns.heatmap(heat, cmap='viridis', ax=ax)" : "ax.imshow(heat, aspect='auto', cmap='viridis')");
      break;
    case "pie":
    case "donut":
      lines.push(aggregateCode(spec, ds, "sum"));
      lines.push(`value_col = ${yNumeric ? y : '"count"'}`);
      lines.push(`ax.pie(agg[value_col], labels=agg[${x}], autopct="%1.1f%%")`);
      if (spec.graphType === "donut") lines.push("ax.add_artist(plt.Circle((0, 0), 0.45, color='white'))");
      lines.push("ax.axis('equal')");
      break;
    case "smooth":
      lines.push(useSeaborn
        ? `sns.regplot(data=df, x=${x}, y=${y}, lowess=True, scatter_kws={"s": ${spec.pointSize * 5}, "alpha": ${spec.opacity}}, ax=ax)`
        : `ax.scatter(df[${x}], df[${y}], s=${spec.pointSize * 5}, marker=${marker}, alpha=${spec.opacity}${markColor})`);
      if (!useSeaborn) lines.push("# Add a smoothing line with scipy/statsmodels if desired.");
      break;
    case "volcano":
      lines.push(`neg_log10_p = -np.log10(np.maximum(pd.to_numeric(df[${y}], errors="coerce"), np.finfo(float).tiny))`);
      lines.push(`ax.scatter(df[${x}], neg_log10_p, s=${spec.pointSize * 5}, marker=${marker}, alpha=${spec.opacity}${markColor})`);
      lines.push('ax.axvline(-1, linestyle="--", color="gray")');
      lines.push('ax.axvline(1, linestyle="--", color="gray")');
      lines.push('ax.axhline(-np.log10(0.05), linestyle="--", color="gray")');
      break;
    case "scatter":
    case "bubble":
    default:
      lines.push(useSeaborn
        ? `sns.scatterplot(data=df, x=${x}, y=${y}${hue ? `, hue=${hue}` : ""}${spec.sizeVar ? `, size=${pystr(spec.sizeVar)}` : ""}${seabornPalette}, ax=ax)`
        : `ax.scatter(df[${x}], df[${y}], s=${spec.sizeVar ? `df[${pystr(spec.sizeVar)}]` : spec.pointSize * 5}${scatterGradient}, marker=${marker}, alpha=${spec.opacity}${spec.colorVar ? "" : markColor})`);
      break;
  }

  if ((spec.stat === "regression" || spec.stat === "average") && spec.graphType === "scatter") {
    if (spec.stat === "regression") {
      lines.push(`fit_df = pd.DataFrame({"x": pd.to_numeric(df[${x}], errors="coerce"), "y": pd.to_numeric(df[${y}], errors="coerce")}).dropna()`);
      lines.push(`if len(fit_df) >= 2:`);
      lines.push(`    coef = np.polyfit(fit_df["x"], fit_df["y"], 1)`);
      lines.push(`    xx = np.array([fit_df["x"].min(), fit_df["x"].max()])`);
      lines.push(`    ax.plot(xx, coef[0] * xx + coef[1], linestyle="--", linewidth=${spec.lineWidth}, color=${pystr(spec.lineColor || "black")})`);
    } else {
      lines.push(`ax.axhline(pd.to_numeric(df[${y}], errors="coerce").mean(), linestyle=":", linewidth=${spec.lineWidth}, color=${pystr(spec.lineColor || "black")})`);
    }
  }

  lines.push(...axisSetupLines(spec));
  if (spec.legendPos === "none") lines.push("legend = ax.get_legend()\nif legend is not None:\n    legend.remove()");
  lines.push("fig.tight_layout()");
  lines.push("plt.show()");
  return lines.join("\n");
}

