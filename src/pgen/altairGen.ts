import { Dataset, PlotSpec } from "../types";
import {
  pystr,
  embedData,
  aggregateCode,
  resolvedSpec,
} from "./pgenHelpers";

function altairEncoding(spec: PlotSpec, yTitle?: string): string[] {
  const axisTitle = (title: string) => spec.showAxisLabels === false ? "" : title;
  const enc = [
    `    x=alt.X(${pystr(spec.xVar)}, title=${pystr(axisTitle(spec.xLabel || spec.xVar))}, axis=alt.Axis(labels=${spec.showXTicks ? "True" : "False"}, labelAngle=${spec.xTickAngle}))`,
  ];
  if (!["histogram", "density", "ecdf", "rug", "pie", "donut", "treemap", "waffle", "table"].includes(spec.graphType)) {
    enc.push(`    y=alt.Y(${pystr(spec.yVar)}, title=${pystr(axisTitle(yTitle ?? (spec.yLabel || spec.yVar)))}, axis=alt.Axis(labels=${spec.showYTicks ? "True" : "False"}, labelAngle=${spec.yTickAngle}))`);
  }
  if (spec.groupVar) enc.push(`    color=alt.Color(${pystr(spec.groupVar)}, legend=${spec.legendPos === "none" ? "None" : "alt.Legend()"})`);
  if (spec.colorVar) enc.push(`    color=alt.Color(${pystr(spec.colorVar)}, scale=alt.Scale(scheme=${pystr(spec.contColorScale.toLowerCase())}), legend=${spec.legendPos === "none" ? "None" : "alt.Legend()"})`);
  if (spec.sizeVar && spec.graphType === "bubble") enc.push(`    size=alt.Size(${pystr(spec.sizeVar)})`);
  if (spec.labelVar) enc.push(`    tooltip=[${[spec.xVar, spec.yVar, spec.groupVar, spec.labelVar].filter(Boolean).map(pystr).join(", ")}]`);
  return enc;
}

export function generateAltairPython(spec: PlotSpec, ds: Dataset): string {
  spec = resolvedSpec(spec, ds);
  const lines: string[] = [
    "# Generated by Iris — Python Altair equivalent.",
    "import numpy as np",
    "import pandas as pd",
    "import altair as alt",
    "from io import StringIO",
    "",
    embedData(ds),
    "",
    "alt.data_transformers.disable_max_rows()",
    `base = alt.Chart(df).properties(width=720, height=460${spec.title ? `, title=${pystr(spec.subtitle ? `${spec.title}\\n${spec.subtitle}` : spec.title)}` : ""})`,
  ];

  if (!spec.xVar || !spec.yVar) {
    lines.push("chart = alt.Chart(pd.DataFrame({'message': ['Add data or assign graph fields to render this chart.']})).mark_text().encode(text='message:N')");
    lines.push("chart");
    return lines.join("\n");
  }

  const x = pystr(spec.xVar);
  const y = pystr(spec.yVar);
  const grp = spec.groupVar ? pystr(spec.groupVar) : "";
  const axisTitle = (title: string) => spec.showAxisLabels === false ? "" : title;
  const yNumeric = ds.types[spec.yVar] === "numeric";

  switch (spec.graphType) {
    case "histogram":
      lines.push("chart = base.mark_bar(opacity=" + spec.opacity + ").encode(");
      lines.push(`    x=alt.X(${x}, bin=alt.Bin(maxbins=${spec.histBins}), title=${pystr(axisTitle(spec.xLabel || spec.xVar))}),`);
      lines.push(`    y=alt.Y('count()', title=${pystr(axisTitle(spec.histNorm === "count" ? "count" : spec.histNorm))}),`);
      if (grp) lines.push(`    color=alt.Color(${grp}),`);
      lines.push(")");
      break;
    case "bar":
    case "lollipop":
      lines.push(aggregateCode(spec, ds));
      lines.push(`value_col = ${yNumeric ? y : '"count"'}`);
      lines.push("base = alt.Chart(agg).properties(width=720, height=460" + (spec.title ? `, title=${pystr(spec.title)}` : "") + ")");
      lines.push("bar = base.mark_bar(opacity=" + spec.opacity + ").encode(");
      lines.push(`    x=alt.X(${x}, title=${pystr(axisTitle(spec.xLabel || spec.xVar))}),`);
      lines.push(`    y=alt.Y(value_col, title=${pystr(axisTitle(spec.yLabel || spec.yVar))}),`);
      lines.push(")");
      lines.push(spec.graphType === "lollipop" ? "chart = bar.mark_rule() + bar.mark_point(size=90)" : "chart = bar");
      break;
    case "line":
    case "timeSeries":
    case "connected":
      lines.push(`chart = base.mark_line(point=${spec.showPoints || spec.graphType === "connected" ? "True" : "False"}, strokeWidth=${spec.lineWidth}).encode(`);
      lines.push(altairEncoding(spec).join(",\n"));
      lines.push(")");
      break;
    case "step":
      lines.push(`chart = base.mark_line(interpolate='step-after', point=${spec.showPoints ? "True" : "False"}, strokeWidth=${spec.lineWidth}).encode(`);
      lines.push(altairEncoding(spec).join(",\n"));
      lines.push(")");
      break;
    case "area":
    case "stackedArea":
    case "stream":
      lines.push(`chart = base.mark_area(opacity=${Math.min(spec.opacity, 0.65)}).encode(`);
      lines.push(altairEncoding(spec).join(",\n"));
      lines.push(")");
      break;
    case "box":
      lines.push("chart = base.mark_boxplot().encode(");
      lines.push(`    x=alt.X(${pystr(spec.groupVar || spec.xVar)}, title=${pystr(axisTitle(spec.groupVar || spec.xVar))}),`);
      lines.push(`    y=alt.Y(${y}, title=${pystr(axisTitle(spec.yLabel || spec.yVar))}),`);
      if (grp) lines.push(`    color=alt.Color(${grp}),`);
      lines.push(")");
      break;
    case "violin":
    case "density":
    case "ridgeline":
      lines.push("# Altair density/violin-style charts are represented as kernel-density areas.");
      lines.push("chart = base.transform_density(");
      lines.push(`    ${x}, as_=[${pystr(spec.xVar)}, 'density']${grp ? `, groupby=[${grp}]` : ""}`);
      lines.push(").mark_area(opacity=0.55).encode(");
      lines.push(`    x=alt.X(${x}, title=${pystr(axisTitle(spec.xLabel || spec.xVar))}),`);
      lines.push(`    y=alt.Y('density:Q', title=${pystr(axisTitle("density"))}),`);
      if (grp) lines.push(`    color=alt.Color(${grp}),`);
      lines.push(")");
      break;
    case "heatmap":
      lines.push("chart = base.mark_rect().encode(");
      lines.push(`    x=alt.X(${x}, title=${pystr(axisTitle(spec.xLabel || spec.xVar))}),`);
      lines.push(`    y=alt.Y(${pystr(spec.groupVar || spec.yVar)}, title=${pystr(axisTitle(spec.groupVar || spec.yVar))}),`);
      lines.push(`    color=alt.Color(${y}, aggregate='mean', scale=alt.Scale(scheme='viridis')),`);
      lines.push(")");
      break;
    case "pie":
    case "donut":
      lines.push(aggregateCode(spec, ds, "sum"));
      lines.push(`value_col = ${yNumeric ? y : '"count"'}`);
      lines.push("chart = alt.Chart(agg).mark_arc(innerRadius=" + (spec.graphType === "donut" ? 70 : 0) + ").encode(");
      lines.push(`    theta=alt.Theta(value_col, type='quantitative'),`);
      lines.push(`    color=alt.Color(${x}, type='nominal'),`);
      lines.push(")");
      break;
    case "smooth":
      lines.push("points = base.mark_point(size=" + spec.pointSize * 8 + ", opacity=" + spec.opacity + ").encode(");
      lines.push(altairEncoding(spec).join(",\n"));
      lines.push(")");
      lines.push("line = points.transform_regression(" + x + ", " + y + ").mark_line()");
      lines.push("chart = points + line");
      break;
    case "volcano":
      lines.push(`df['_neg_log10_p'] = -np.log10(np.maximum(pd.to_numeric(df[${y}], errors='coerce'), np.finfo(float).tiny))`);
      lines.push("chart = alt.Chart(df).mark_point(size=" + spec.pointSize * 8 + ", opacity=" + spec.opacity + ").encode(");
      lines.push(`    x=alt.X(${x}, title=${pystr(axisTitle(spec.xLabel || spec.xVar))}),`);
      lines.push(`    y=alt.Y('_neg_log10_p:Q', title=${pystr(axisTitle("-log10(p-value)"))}),`);
      if (grp) lines.push(`    color=alt.Color(${grp}),`);
      lines.push(")");
      break;
    case "scatter":
    case "bubble":
    default:
      lines.push("chart = base.mark_point(size=" + spec.pointSize * 8 + ", opacity=" + spec.opacity + ").encode(");
      lines.push(altairEncoding(spec).join(",\n"));
      lines.push(")");
      break;
  }

  lines.push("");
  lines.push("# In notebooks, display with: chart");
  lines.push("# Save with: chart.save('figure.html') or chart.save('figure.png') if vl-convert-python is installed.");
  lines.push("chart");
  return lines.join("\n");
}

