import { Dataset, PlotSpec, PALETTES } from "../types";
import {
  rstr,
  q,
  embedData,
  paletteVec,
  discreteLevels,
  lineColour,
  pointShape,
  cleanLibraries,
  resolvedSpec,
} from "./rEmbedder";

import {
  lineType,
  errorFun,
  paletteScales,
  contFillScale,
  contColourScale,
  themeCall,
  labsLine,
} from "./rPlotHelpers";

export function generateR(spec: PlotSpec, ds: Dataset, libraries: string[] = []): string {
  spec = resolvedSpec(spec, ds);
  const levels = discreteLevels(spec, ds);
  const lines: string[] = [];
  lines.push("# Generated by Iris — edit freely, then Run / Export.");
  lines.push("library(ggplot2)");
  cleanLibraries(libraries).forEach((lib) => lines.push(`library(${lib})`));
  lines.push("");
  lines.push(embedData(ds));
  lines.push("");

  const grp = spec.colorVar ? "" : spec.groupVar;
  const gradientVar = spec.colorVar;
  const labelLayer = spec.labelVar ? `  geom_text(aes(label = ${q(spec.labelVar)}), vjust = -0.8, size = ${spec.labelSize / 3}, check_overlap = TRUE) +\n` : "";
  const yIsNumeric = ds.types[spec.yVar] === "numeric";
  let body = "";

  switch (spec.graphType) {
    case "pie":
    case "donut": {
      if (yIsNumeric) {
        body += `agg <- aggregate(list(value = df[[${rstr(spec.yVar)}]]), by = list(cat = df[[${rstr(spec.xVar)}]]), FUN = sum)\n`;
        if (ds.types[spec.xVar] === "numeric") body += `agg$cat <- factor(agg$cat)\n`;
      } else {
        body += `agg <- as.data.frame(table(cat = df[[${rstr(spec.xVar)}]])); names(agg)[2] <- "value"\n`;
      }
      if (spec.pieExplode > 0) {
        body += `# Slice 'explode' (pull = ${spec.pieExplode}) is shown in the live preview; ggplot2 pie/doughnut charts can't offset slices directly.\n`;
      }
      const xExpr = spec.graphType === "donut" ? "2" : '""';
      body += `p <- ggplot(agg, aes(x = ${xExpr}, y = value, fill = cat)) +\n`;
      body += `  geom_col(width = 1, colour = "white", alpha = ${spec.opacity}) +\n`;
      body += `  coord_polar(theta = "y") +\n`;
      if (spec.graphType === "donut") {
        const lower = Math.max(0, Math.min(1.4, (1.5 - 2.5 * spec.donutHole) / (1 - spec.donutHole)));
        body += `  xlim(${lower.toFixed(2)}, 2.5) +\n`;
      }
      body += `  scale_fill_manual(values = ${paletteVec(spec, levels)}) +\n`;
      body += `  labs(fill = ${rstr(spec.xVar)}${spec.title ? `, title = ${rstr(spec.title)}` : ""}) +\n`;
      body += `  theme_void(base_size = ${spec.baseFontSize}, base_family = ${rstr(spec.fontFamily)}) +\n`;
      body += `  theme(legend.position = ${spec.legendPos === "none" ? '"none"' : `"${spec.legendPos}"`}, plot.title = element_text(face = "bold", hjust = 0.5))`;
      break;
    }
    case "heatmap": {
      const yCol = grp || spec.yVar;
      body += `agg <- aggregate(list(value = df[[${rstr(spec.yVar)}]]), by = list(xv = df[[${rstr(spec.xVar)}]], yv = df[[${rstr(yCol)}]]), FUN = mean)\n`;
      body += `p <- ggplot(agg, aes(x = xv, y = yv, fill = value)) +\n`;
      body += `  geom_tile(colour = "white", linewidth = 0.4) +\n`;
      body += contFillScale(spec, spec.yVar);
      body += labsLine(spec, { yLabel: spec.yLabel || yCol });
      body += themeCall(spec);
      break;
    }
    case "density2d": {
      body += `p <- ggplot(df, aes(x = ${q(spec.xVar)}, y = ${q(spec.yVar)})) +\n`;
      body += `  geom_density_2d_filled(alpha = ${spec.opacity}) +\n`;
      body += labsLine(spec);
      body += themeCall(spec);
      break;
    }
    case "hexbin": {
      body += `p <- ggplot(df, aes(x = ${q(spec.xVar)}, y = ${q(spec.yVar)})) +\n`;
      body += `  stat_bin_2d(bins = ${spec.histBins}, alpha = ${spec.opacity}) +\n`;
      body += contFillScale(spec, "count");
      body += labsLine(spec);
      body += themeCall(spec);
      break;
    }
    case "table": {
      body += `txt <- paste(capture.output(utils::head(df, 12)), collapse = "\\n")\n`;
      body += `p <- ggplot() + annotate("text", x = 0, y = 1, label = txt, hjust = 0, vjust = 1, family = "mono", size = 3) + xlim(0, 1) + ylim(0, 1) + theme_void()`;
      break;
    }
    case "correlogram": {
      const nums = ds.columns.filter((c) => ds.types[c] === "numeric");
      body += `num_cols <- c(${nums.map(rstr).join(", ")})\n`;
      body += `cm <- cor(df[, num_cols], use = "pairwise.complete.obs")\n`;
      body += `corr_df <- as.data.frame(as.table(cm)); names(corr_df) <- c("x", "y", "r")\n`;
      body += `p <- ggplot(corr_df, aes(x = x, y = y, fill = r)) +\n`;
      body += `  geom_tile(colour = "white") +\n  scale_fill_gradient2(low = "#2166ac", mid = "white", high = "#b2182b", limits = c(-1, 1)) +\n`;
      body += labsLine(spec, { yLabel: "" });
      body += themeCall(spec);
      break;
    }
    case "radar":
    case "parallel": {
      const nums = ds.columns.filter((c) => ds.types[c] === "numeric");
      body += `num_cols <- c(${nums.map(rstr).join(", ")})\n`;
      body += `long <- stack(df[, num_cols]); long$row_id <- rep(seq_len(nrow(df)), times = length(num_cols))\n`;
      if (grp) body += `long$group <- rep(df[[${rstr(grp)}]], times = length(num_cols))\n`;
      body += `p <- ggplot(long, aes(x = ind, y = values${grp ? ', colour = group' : ''}${spec.graphType === "parallel" ? ', group = row_id' : ', group = 1'})) +\n`;
      body += spec.graphType === "radar" ? `  stat_summary(fun = mean, geom = "line", linewidth = ${spec.lineWidth / 2}) + coord_polar() +\n` : `  geom_line(alpha = 0.35) +\n`;
      body += labsLine(spec, { yLabel: spec.graphType === "radar" ? "mean value" : "value" });
      body += themeCall(spec);
      break;
    }
    case "treemap":
    case "waffle":
    case "circularBar": {
      body += `agg <- aggregate(list(value = df[[${rstr(spec.yVar)}]]), by = list(cat = df[[${rstr(spec.xVar)}]]), FUN = sum)\n`;
      if (ds.types[spec.xVar] === "numeric") body += `agg$cat <- factor(agg$cat)\n`;
      body += `p <- ggplot(agg, aes(x = reorder(cat, value), y = value, fill = cat)) +\n`;
      body += spec.graphType === "circularBar" ? `  geom_col(alpha = ${spec.opacity}) + coord_polar() +\n` : `  geom_col(alpha = ${spec.opacity}, colour = "white") + coord_flip() +\n`;
      body += paletteScales(spec, levels);
      body += labsLine(spec);
      body += themeCall(spec);
      break;
    }
    case "lollipop": {
      const col = (PALETTES[spec.palette] ?? PALETTES.prism)[0];
      body += `agg <- aggregate(list(value = df[[${rstr(spec.yVar)}]]), by = list(cat = df[[${rstr(spec.xVar)}]]), FUN = mean)\n`;
      body += `p <- ggplot(agg, aes(x = cat, y = value)) +\n`;
      body += `  geom_segment(aes(x = cat, xend = cat, y = 0, yend = value), colour = "${lineColour(spec)}", linewidth = ${spec.lineWidth / 2}) +\n`;
      body += `  geom_point(colour = "${col}", shape = ${pointShape(spec)}, size = ${spec.pointSize / 2}) +\n`;
      body += labsLine(spec);
      if (spec.orientation === "horizontal") body += `  coord_flip() +\n`;
      body += themeCall(spec);
      break;
    }
    case "volcano": {
      const yexpr = `-log10(pmax(${q(spec.yVar)}, .Machine$double.xmin))`;
      const fc = spec.volcanoFcCut;
      const pcut = spec.volcanoPCut;
      if (spec.volcanoColorBySig) {
        body += `df$Significance <- factor(ifelse(df[[${rstr(spec.xVar)}]] >= ${fc} & df[[${rstr(spec.yVar)}]] <= ${pcut}, "Up",\n`;
        body += `                          ifelse(df[[${rstr(spec.xVar)}]] <= ${-fc} & df[[${rstr(spec.yVar)}]] <= ${pcut}, "Down", "NS")),\n`;
        body += `                   levels = c("Up", "Down", "NS"))\n`;
        body += `p <- ggplot(df, aes(x = ${q(spec.xVar)}, y = ${yexpr}, colour = Significance)) +\n`;
        body += `  geom_point(shape = ${pointShape(spec)}, size = ${spec.pointSize / 2.5}, stroke = ${spec.pointStroke / 2}, alpha = ${spec.opacity}) +\n`;
        body += `  scale_colour_manual(values = c(Up = "#E4572E", Down = "#1F77B4", NS = "#9aa0a6")) +\n`;
        if (spec.volcanoLabelSig && spec.labelVar) {
          body += `  geom_text(data = subset(df, Significance != "NS"), aes(label = ${q(spec.labelVar)}), vjust = -0.8, size = ${spec.labelSize / 3}, show.legend = FALSE, check_overlap = TRUE) +\n`;
        }
      } else {
        body += `p <- ggplot(df, aes(x = ${q(spec.xVar)}, y = ${yexpr}${grp ? `, colour = ${q(grp)}` : ""})) +\n`;
        body += `  geom_point(shape = ${pointShape(spec)}, size = ${spec.pointSize / 2.5}, stroke = ${spec.pointStroke / 2}, alpha = ${spec.opacity}) +\n`;
        body += paletteScales(spec, levels);
      }
      body += `  geom_vline(xintercept = c(${-fc}, ${fc}), linetype = "dashed", colour = "grey55") +\n`;
      body += `  geom_hline(yintercept = -log10(${pcut}), linetype = "dashed", colour = "grey55") +\n`;
      body += labsLine(spec);
      body += themeCall(spec);
      break;
    }
    default: {
      const aesColour = gradientVar ? `, colour = ${q(gradientVar)}, fill = ${q(gradientVar)}` : grp ? `, colour = ${q(grp)}, fill = ${q(grp)}` : "";
      const gradientScale = gradientVar ? contColourScale(spec, gradientVar) : "";
      let aes = "";
      let geom = "";
      switch (spec.graphType) {
        case "scatter":
          aes = `aes(x = ${q(spec.xVar)}, y = ${q(spec.yVar)}${aesColour})`;
          geom = `  geom_point(shape = ${pointShape(spec)}, size = ${spec.pointSize / 2.5}, stroke = ${spec.pointStroke / 2}, alpha = ${spec.opacity}) +\n`;
          geom += labelLayer;
          if (spec.stat === "regression") geom += `  geom_smooth(method = "lm", se = TRUE, linewidth = ${spec.lineWidth / 2}) +\n`;
          if (spec.stat === "average") geom += `  geom_hline(yintercept = mean(df[[${rstr(spec.yVar)}]], na.rm = TRUE), linetype = "dotted", linewidth = ${spec.lineWidth / 2}, colour = "${lineColour(spec)}") +\n`;
          break;
        case "bubble":
          aes = `aes(x = ${q(spec.xVar)}, y = ${q(spec.yVar)}${spec.sizeVar ? `, size = ${q(spec.sizeVar)}` : ""}${aesColour})`;
          geom = `  geom_point(shape = ${pointShape(spec)}, alpha = ${Math.min(spec.opacity, 0.75)}) +\n  scale_size(range = c(2, 12)) +\n`;
          geom += labelLayer;
          break;
        case "line":
        case "timeSeries":
          aes = `aes(x = ${q(spec.xVar)}, y = ${q(spec.yVar)}${aesColour}${grp ? `, group = ${q(grp)}` : ""})`;
          geom = `  geom_line(linewidth = ${spec.lineWidth / 2}, linetype = ${rstr(lineType(spec))}, colour = "${lineColour(spec)}", alpha = ${spec.opacity}) +\n`;
          if (spec.showPoints) geom += `  geom_point(shape = ${pointShape(spec)}, size = ${spec.pointSize / 2.5}, stroke = ${spec.pointStroke / 2}) +\n`;
          geom += labelLayer;
          break;
        case "connected":
          aes = `aes(x = ${q(spec.xVar)}, y = ${q(spec.yVar)}${aesColour}${grp ? `, group = ${q(grp)}` : ""})`;
          geom = `  geom_path(linewidth = ${spec.lineWidth / 2}, linetype = ${rstr(lineType(spec))}, colour = "${lineColour(spec)}", alpha = ${spec.opacity}) +\n  geom_point(shape = ${pointShape(spec)}, size = ${spec.pointSize / 2.5}, stroke = ${spec.pointStroke / 2}) +\n`;
          geom += labelLayer;
          break;
        case "step":
          aes = `aes(x = ${q(spec.xVar)}, y = ${q(spec.yVar)}${aesColour}${grp ? `, group = ${q(grp)}` : ""})`;
          geom = `  geom_step(linewidth = ${spec.lineWidth / 2}, linetype = ${rstr(lineType(spec))}, colour = "${lineColour(spec)}", alpha = ${spec.opacity}) +\n`;
          if (spec.showPoints) geom += `  geom_point(shape = ${pointShape(spec)}, size = ${spec.pointSize / 2.5}, stroke = ${spec.pointStroke / 2}) +\n`;
          geom += labelLayer;
          break;
        case "smooth":
          aes = `aes(x = ${q(spec.xVar)}, y = ${q(spec.yVar)}${aesColour}${grp ? `, group = ${q(grp)}` : ""})`;
          if (spec.showPoints) geom = `  geom_point(shape = ${pointShape(spec)}, size = ${spec.pointSize / 2.5}, stroke = ${spec.pointStroke / 2}, alpha = ${Math.min(spec.opacity, 0.55)}) +\n` + labelLayer;
          geom += `  geom_smooth(method = "loess", se = ${spec.showErrorEnvelope ? "TRUE" : "FALSE"}, linewidth = ${spec.lineWidth / 2}, linetype = ${rstr(lineType(spec))}, colour = "${lineColour(spec)}", alpha = ${spec.opacity * 0.35}) +\n`;
          break;
        case "area":
        case "stackedArea":
        case "stream":
          aes = `aes(x = ${q(spec.xVar)}, y = ${q(spec.yVar)}${aesColour}${grp ? `, group = ${q(grp)}` : ""})`;
          geom = `  geom_area(position = "${["stackedArea", "stream"].includes(spec.graphType) || spec.stacked ? "stack" : "identity"}", alpha = ${spec.opacity}, colour = "${lineColour(spec)}", linewidth = ${spec.barBorderWidth / 2}) +\n`;
          break;
        case "ridgeline":
        case "density":
          aes = `aes(x = ${q(spec.xVar)}${aesColour})`;
          geom = spec.graphType === "ridgeline" && grp
            ? `  geom_density(aes(y = after_stat(density + group - 1), group = ${q(grp)}), alpha = ${spec.opacity * 0.5}) +\n` +
              `  scale_y_continuous(breaks = seq_along(levels(factor(df[[${rstr(grp)}]]))) - 1, labels = levels(factor(df[[${rstr(grp)}]]))) +\n`
            : `  geom_density(alpha = ${spec.opacity * 0.6}) +\n`;
          break;
        case "ecdf":
          aes = `aes(x = ${q(spec.xVar)}${grp ? `, colour = ${q(grp)}` : ""})`;
          geom = `  stat_ecdf(linewidth = ${spec.lineWidth / 2}, linetype = ${rstr(lineType(spec))}, alpha = ${spec.opacity}) +\n`;
          break;
        case "rug":
          aes = `aes(x = ${q(spec.xVar)}${grp ? `, colour = ${q(grp)}` : ""})`;
          geom = `  geom_rug(linewidth = ${spec.lineWidth / 3}, alpha = ${spec.opacity}, sides = "b") +\n  scale_y_continuous(NULL, breaks = NULL) +\n`;
          break;
        case "bar":
          aes = `aes(x = ${q(spec.xVar)}, y = ${q(spec.yVar)}${aesColour})`;
          geom = `  stat_summary(fun = mean, geom = "bar", position = position_dodge(0.9), width = ${spec.barWidth}, alpha = ${spec.opacity}, colour = "black", linewidth = ${spec.barBorderWidth / 2}) +\n`;
          if (spec.barError !== "none") {
            geom += `  stat_summary(fun.min = ${errorFun(spec)}, geom = "errorbar", linewidth = ${spec.errorCapThickness / 2}, width = 0.2, position = position_dodge(0.9)) +\n`;
          }
          break;
        case "errorBar":
          aes = `aes(x = ${q(spec.xVar)}, y = ${q(spec.yVar)}${aesColour})`;
          geom = `  stat_summary(fun = mean, geom = "bar", position = position_dodge(0.9), width = ${spec.barWidth}, alpha = ${spec.opacity}, colour = "black", linewidth = ${spec.barBorderWidth / 2}) +\n`;
          geom += `  stat_summary(fun.min = ${errorFun(spec)}, geom = "errorbar", linewidth = ${spec.errorCapThickness / 2}, width = 0.2, position = position_dodge(0.9)) +\n`;
          break;
        case "dotPlot":
          aes = `aes(x = ${q(spec.xVar)}, y = ${q(spec.yVar)}${aesColour})`;
          geom = `  stat_summary(fun = mean, geom = "point", shape = ${pointShape(spec)}, size = ${spec.pointSize / 2.5}, alpha = ${spec.opacity}) +\n`;
          break;
        case "forest":
          aes = `aes(x = ${q(spec.yVar)}, y = ${q(spec.xVar)}${aesColour})`;
          geom = `  geom_point(shape = ${pointShape(spec)}, size = ${spec.pointSize / 2.5}, alpha = ${spec.opacity}) +\n`;
          if (spec.sizeVar) geom += `  geom_errorbarh(aes(xmin = ${q(spec.yVar)} - abs(${q(spec.sizeVar)}), xmax = ${q(spec.yVar)} + abs(${q(spec.sizeVar)})), height = 0.2) +\n`;
          geom += `  geom_vline(xintercept = 0, linetype = "dashed", colour = "grey60") +\n`;
          break;
        case "slope":
          aes = `aes(x = ${q(spec.xVar)}, y = ${q(spec.yVar)}${aesColour}${grp ? `, group = ${q(grp)}` : ""})`;
          geom = `  geom_line(linewidth = ${spec.lineWidth / 2}, alpha = ${spec.opacity}) +\n  geom_point(shape = ${pointShape(spec)}, size = ${spec.pointSize / 2.5}) +\n`;
          geom += labelLayer;
          break;
        case "qq":
          aes = `aes(sample = ${q(spec.xVar)}${grp ? `, colour = ${q(grp)}` : ""})`;
          geom = `  stat_qq(shape = ${pointShape(spec)}, size = ${spec.pointSize / 2.5}, alpha = ${spec.opacity}) +\n  stat_qq_line(linewidth = ${spec.lineWidth / 2}) +\n`;
          break;
        case "blandAltman":
          aes = `aes(x = (${q(spec.xVar)} + ${q(spec.yVar)}) / 2, y = ${q(spec.yVar)} - ${q(spec.xVar)}${grp ? `, colour = ${q(grp)}` : ""})`;
          geom = `  geom_point(shape = ${pointShape(spec)}, size = ${spec.pointSize / 2.5}, alpha = ${spec.opacity}) +\n`;
          geom += `  geom_hline(yintercept = mean(df[[${rstr(spec.yVar)}]] - df[[${rstr(spec.xVar)}]], na.rm = TRUE), linetype = "dashed") +\n`;
          geom += `  geom_hline(yintercept = mean(df[[${rstr(spec.yVar)}]] - df[[${rstr(spec.xVar)}]], na.rm = TRUE) + c(-1, 1) * 1.96 * sd(df[[${rstr(spec.yVar)}]] - df[[${rstr(spec.xVar)}]], na.rm = TRUE), linetype = "dotted", colour = "grey55") +\n`;
          break;
        case "manhattan":
          aes = `aes(x = ${q(spec.xVar)}, y = -log10(pmax(${q(spec.yVar)}, .Machine$double.xmin))${grp ? `, colour = ${q(grp)}` : ""})`;
          geom = `  geom_point(shape = ${pointShape(spec)}, size = ${spec.pointSize / 2.8}, alpha = ${spec.opacity}) +\n`;
          break;
        case "facet":
          {
            const fVar = spec.facetVar || grp;
            aes = `aes(x = ${q(spec.xVar)}, y = ${q(spec.yVar)}${aesColour})`;
            geom = `  geom_point(shape = ${pointShape(spec)}, size = ${spec.pointSize / 2.5}, alpha = ${spec.opacity}) +\n`;
            if (fVar) geom += `  facet_wrap(~ ${q(fVar)}) +\n`;
          }
          break;
        case "box":
          aes = `aes(x = ${q(grp || spec.xVar)}, y = ${q(spec.yVar)}${grp ? `, fill = ${q(grp)}` : ""})`;
          geom = `  geom_boxplot(alpha = ${spec.opacity}, outlier.shape = ${spec.showPoints ? "NA" : "19"}) +\n`;
          if (spec.showPoints) geom += `  geom_jitter(width = 0.15, shape = ${pointShape(spec)}, size = ${spec.pointSize / 3}, stroke = ${spec.pointStroke / 2}, alpha = 0.6) +\n`;
          break;
        case "beeswarm":
          aes = `aes(x = ${q(grp || spec.xVar)}, y = ${q(spec.yVar)}${grp ? `, colour = ${q(grp)}` : ""})`;
          geom = `  geom_jitter(width = 0.2, shape = ${pointShape(spec)}, size = ${spec.pointSize / 2.5}, stroke = ${spec.pointStroke / 2}, alpha = ${spec.opacity}) +\n`;
          break;
        case "strip":
          aes = `aes(x = ${q(grp || spec.xVar)}, y = ${q(spec.yVar)}${grp ? `, colour = ${q(grp)}` : ""})`;
          geom = `  geom_jitter(width = 0.12, height = 0, shape = ${pointShape(spec)}, size = ${spec.pointSize / 2.5}, stroke = ${spec.pointStroke / 2}, alpha = ${spec.opacity}) +\n`;
          break;
        case "violin":
          aes = `aes(x = ${q(grp || spec.xVar)}, y = ${q(spec.yVar)}${grp ? `, fill = ${q(grp)}` : ""})`;
          geom = `  geom_violin(alpha = ${spec.opacity}, trim = FALSE) +\n  geom_boxplot(width = 0.12, alpha = 0.7, outlier.shape = NA) +\n`;
          if (spec.showPoints) geom += `  geom_jitter(width = 0.1, shape = ${pointShape(spec)}, size = ${spec.pointSize / 3}, stroke = ${spec.pointStroke / 2}, alpha = 0.5) +\n`;
          break;
        case "histogram": {
          const yAes = spec.histNorm === "density" ? ", y = after_stat(density)" : spec.histNorm === "percent" ? ", y = after_stat(count / sum(count) * 100)" : "";
          aes = `aes(x = ${q(spec.xVar)}${yAes}${grp ? `, fill = ${q(grp)}` : ""})`;
          geom = `  geom_histogram(bins = ${spec.histBins}, alpha = ${spec.opacity}, position = "identity", colour = "white") +\n`;
          break;
        }
        default:
          geom = `  # ${spec.graphType} is shown in the live Plotly preview. This ggplot2 export uses a dependency-free scatter approximation.\n`;
          aes = `aes(x = ${q(spec.xVar)}, y = ${q(spec.yVar)}${aesColour})`;
          geom += `  geom_point(shape = ${pointShape(spec)}, size = ${spec.pointSize / 2.5}, stroke = ${spec.pointStroke / 2}, alpha = ${spec.opacity}) +\n`;
          geom += labelLayer;
          break;
      }

      body = `p <- ggplot(df, ${aes}) +\n${geom}${gradientScale || paletteScales(spec, levels)}`;
      body += labsLine(spec);
      if (spec.orientation === "horizontal" && ["bar", "errorBar", "dotPlot", "box", "violin", "beeswarm", "strip"].includes(spec.graphType)) {
        body += `  coord_flip() +\n`;
      }

      if (spec.xTickStep !== "") {
        body += `  scale_x_continuous(breaks = function(x) seq(floor(min(x, na.rm = TRUE) / ${spec.xTickStep}) * ${spec.xTickStep}, ceiling(max(x, na.rm = TRUE) / ${spec.xTickStep}) * ${spec.xTickStep}, by = ${spec.xTickStep})) +\n`;
      }
      if (spec.yTickStep !== "" && !spec.logY) {
        body += `  scale_y_continuous(breaks = function(y) seq(floor(min(y, na.rm = TRUE) / ${spec.yTickStep}) * ${spec.yTickStep}, ceiling(max(y, na.rm = TRUE) / ${spec.yTickStep}) * ${spec.yTickStep}, by = ${spec.yTickStep})) +\n`;
      }
      if (spec.logY && !["histogram", "density", "ecdf", "rug"].includes(spec.graphType)) {
        body += `  scale_y_log10() +\n`;
      } else if (spec.yMin !== "" && spec.yMax !== "") {
        body += `  coord_cartesian(ylim = c(${spec.yMin}, ${spec.yMax})) +\n`;
      }
      if (spec.xMin !== "" && spec.xMax !== "" && ["scatter", "line", "step", "area", "bubble", "density", "histogram", "ecdf", "rug", "smooth", "hexbin"].includes(spec.graphType)) {
        body += `  coord_cartesian(xlim = c(${spec.xMin}, ${spec.xMax})) +\n`;
      }
      if (spec.facetVar && spec.facetVar.trim() !== "" && spec.graphType !== "facet") {
        body += `  facet_wrap(~ ${q(spec.facetVar)}) +\n`;
      }
      body += themeCall(spec);
    }
  }

  lines.push(body);
  lines.push("");
  lines.push("p");
  return lines.join("\n");
}
